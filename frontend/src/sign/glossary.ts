const key = (word: string) => word.toLowerCase().replace(/[’‘]/g, "'").trim();

/** How many sign words have a Filipino entry (for the checks). */
export const GLOSSARY_SIZE = Object.keys(FILIPINO).length;

/** One sign word in Filipino, or null if it isn't a known sign (a name, a spelled word). */
export function signWordInFilipino(word: string): string | null {
  return FILIPINO[key(word)] ?? null;
}

/** Signed words → Filipino, word by word; unknown words (names, spelled words) stay as they are. */
export function signedWordsInFilipino(words: string[]): string {
  return words.map((word) => signWordInFilipino(word) ?? word).join(' ');
}
